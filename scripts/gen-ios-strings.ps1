# Converts the Android string resources into iOS .strings files, so both apps share one
# source of wording and keys (spec: .kiro/specs/ios-app, design "Strings").
#   app/src/main/res/values/strings.xml     -> ios/KeepGoing/Resources/en.lproj
#   app/src/main/res/values-zh/strings.xml  -> ios/KeepGoing/Resources/zh-Hans.lproj and zh-Hant.lproj
# Writes Localizable.strings and InfoPlist.strings. Runs on Windows PowerShell 5.1 and pwsh 7 (CI).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$res = Join-Path $root 'app/src/main/res'
$out = Join-Path $root 'ios/KeepGoing/Resources'

function Read-AndroidStrings([string]$path) {
    $doc = New-Object System.Xml.XmlDocument
    $doc.PreserveWhitespace = $true
    $doc.Load($path)
    $map = [ordered]@{}
    foreach ($node in $doc.DocumentElement.ChildNodes) {
        if ($node.NodeType -ne [System.Xml.XmlNodeType]::Element) { continue }
        if ($node.LocalName -ne 'string') { throw "Unsupported resource <$($node.LocalName)> in $path" }
        $map[$node.GetAttribute('name')] = [pscustomobject]@{
            Text         = Convert-AndroidEscapes $node.InnerText
            Translatable = $node.GetAttribute('translatable') -ne 'false'
        }
    }
    return $map
}

# Android resource escapes: \n \t \' \" \\ \@ \?  (XML entities are already decoded by the parser).
function Convert-AndroidEscapes([string]$s) {
    $sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $s.Length; $i++) {
        $c = $s[$i]
        if ($c -eq '\' -and $i + 1 -lt $s.Length) {
            $i++
            switch -CaseSensitive ($s[$i]) {
                'n' { [void]$sb.Append("`n") }
                't' { [void]$sb.Append("`t") }
                default { [void]$sb.Append($s[$i]) }
            }
        } else {
            [void]$sb.Append($c)
        }
    }
    return $sb.ToString()
}

# Positional Java format specifiers -> Foundation: %1$s -> %1$@, %1$d -> %1$ld, %1$02X -> %1$02lX.
# Only positional specifiers are touched, so a literal "%" in a string without arguments stays as is.
function Convert-Format([string]$s) {
    return [regex]::Replace($s, '%(\d+)\$([-+ 0#]*\d*(?:\.\d+)?)([a-zA-Z])', {
            param($m)
            $conv = $m.Groups[3].Value
            $mapped = switch -CaseSensitive ($conv) {
                's' { '@' }
                'd' { 'ld' }
                'x' { 'lx' }
                'X' { 'lX' }
                'f' { 'f' }
                default { throw "Unsupported format specifier '$($m.Value)'" }
            }
            '%' + $m.Groups[1].Value + '$' + $m.Groups[2].Value + $mapped
        })
}

function Format-StringsValue([string]$s) {
    return $s.Replace('\', '\\').Replace('"', '\"').Replace("`n", '\n').Replace("`t", '\t')
}

function Write-Utf8([string]$path, [string]$text) {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
}

function Write-Language([string]$lproj, $strings, $fallback) {
    $header = "/* Generated by scripts/gen-ios-strings.ps1 from the Android values and values-zh strings.xml. Do not edit. */`n"
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($key in $fallback.Keys) {
        # iOS does not fall back to English per key, so every key is written to every language.
        $entry = if ($strings.Contains($key)) { $strings[$key] } else { $fallback[$key] }
        $lines.Add('"' + $key + '" = "' + (Format-StringsValue (Convert-Format $entry.Text)) + '";')
    }
    Write-Utf8 (Join-Path $out "$lproj/Localizable.strings") ($header + ($lines -join "`n") + "`n")

    $name = if ($strings.Contains('app_name')) { $strings['app_name'].Text } else { $fallback['app_name'].Text }
    $bt = if ($strings.Contains('ios_bt_usage')) { $strings['ios_bt_usage'].Text } else { $fallback['ios_bt_usage'].Text }
    $plist = $header +
        '"CFBundleDisplayName" = "' + (Format-StringsValue $name) + "`";`n" +
        '"NSBluetoothAlwaysUsageDescription" = "' + (Format-StringsValue $bt) + "`";`n"
    Write-Utf8 (Join-Path $out "$lproj/InfoPlist.strings") $plist
    return $lines.Count
}

try {
    $en = Read-AndroidStrings (Join-Path $res 'values/strings.xml')
    $zh = Read-AndroidStrings (Join-Path $res 'values-zh/strings.xml')

    $missing = @($en.Keys | Where-Object { $en[$_].Translatable -and -not $zh.Contains($_) })
    if ($missing.Count -gt 0) { throw "Missing Chinese translations: $($missing -join ', ')" }
    $extra = @($zh.Keys | Where-Object { -not $en.Contains($_) })
    if ($extra.Count -gt 0) { throw "Chinese keys without an English default: $($extra -join ', ')" }

    $n = Write-Language 'en.lproj' $en $en
    [void](Write-Language 'zh-Hans.lproj' $zh $en)
    [void](Write-Language 'zh-Hant.lproj' $zh $en)
    Write-Output "Wrote $n strings to $out (en, zh-Hans, zh-Hant)"
} catch {
    if ($env:GITHUB_ACTIONS) { Write-Output "::error title=gen-ios-strings::$($_.Exception.Message)" }
    throw
}
